const cache = new Map();
/** Ritar en sprite som en liten bild (16×16), sparad för återanvändning. */
export function sprite(name, flip = false) {
  const key = `${name}${flip ? ':f' : ''}`;
  if (cache.has(key)) return cache.get(key);
  const rows = SPRITES[name];
  const c = typeof OffscreenCanvas === 'function' ? new OffscreenCanvas(16, 16) : Object.assign(document.createElement('canvas'), { width: 16, height: 16 });
  const g = c.getContext('2d');
  rows.forEach((row, y) => [...row.padEnd(16, '.')].slice(0, 16).forEach((ch, x) => {
    if (ch === '.') return;
    g.fillStyle = P[ch];
    g.fillRect(flip ? 15 - x : x, y, 1, 1);
  }));
  cache.set(key, c);
  return c;
}
